import os
import shutil
import zipfile

def package():
    dist_dir = os.path.join("dist", "シフト_v1.9")
    assert os.path.isdir(dist_dir), f"Dist dir not found: {dist_dir}"
    
    # 1. 勤務条件表_ひな形.xlsx の配置 (最新のv1.9: 高橋の有休・小島の指定公休日・15項目設定シート入り)
    src_excel = "勤務条件表_9.xlsx"
    dst_excel = os.path.join(dist_dir, "勤務条件表_ひな形.xlsx")
    shutil.copy2(src_excel, dst_excel)
    print(f"ひな形Excelをコピーしました: {dst_excel}")
    
    # 2. 使い方.txt の作成
    readme_path = os.path.join(dist_dir, "使い方.txt")
    readme_content = """【勤務シフト自動生成システム v1.9 使い方ガイド】

1. 起動方法
   「シフト_v1.9.exe」をダブルクリックして起動します。
   （Pythonのインストールは不要です）

2. 条件表の準備
   同じフォルダ内にある「勤務条件表_ひな形.xlsx」を編集、
   またはご自身の「*勤務条件表*.xlsx」をこのフォルダ内に配置してください。

3. 作成対象月の選択
   手術スケジュールシートに記載のあるすべての月が自動的に一覧表示されます。
   生成したい月にチェックを入れてください（「全選択」「全解除」ボタンも利用可能）。

4. 指定公休日の日付指定HARD適用＆全日付形式対応 (v1.8 / v1.9強化)
   ・スタッフマスタの「指定公休日」列に具体的な日付（例:「2026/11/16」「11月16日」「11/16」など）を記入すると、
     公休日（記号「公」）が【HARD制約】として強制設定されます。
   ・夏期休暇（特別有休）の前後に設定することで、公休と合わせた大型連休を確実に形成できます。
   ・v1.9では、ハイフン区切り（2026-11-10）、スラッシュ区切り（2026/11/16）、日本語日付書式（11月16日・Excel日付シリアル値）、
     全角文字など、あらゆるExcel入力形式を自動判別し、実行ログにも検出された有休・特有・指定公休日を一覧表示します。
   ・指定公休日がある週は、指定公休日がその週の公休となるため、主公休曜日の強制休み義務が自動免除（振替）され、
     月間の所定出勤日数や他の週の勤務と矛盾しないよう自動調整されます。

5. 1階勤務人数のパート込み平準化＆6名回避機能 (v1.7)
   ・1階セクションの平準化において、パートの固定出勤（曜日指定）をソルバーが事前に把握し、
     正社員＋パートの全体人数で毎日がフラット（平均7名）になるよう自動調整します。
   ・パートが1名の日（火・水・土）は正社員を多めに（6名）、パートが2名の日（月・木・金）は正社員を適正に配置し、
     1階の総勤務人数が「6名」となる事態を極力回避して7〜8名を安定確保します。
   ・将来スタッフの退職・新規加入・パートの曜日変更があった場合でも、「スタッフマスタ」を更新するだけで
     自動的に最新の在籍人数に応じた適正平準化へと自動追従します。

6. 公休・人数の週単位平準化ルール (v1.6)
   ・勤務パターン適応型週休目標: 週4日勤務者は週休3日（日曜1＋公休2）、週5日勤務者は週休2日（日曜1＋公休1）を基準にローリング平準化を適用。
   ・カレンダー週単位の公休平準化: 週4日勤務者は各週の公休が原則2日（祝日週は1日）となるよう平準化され、特定週への偏りや連休・連勤の偏りを防止。
   ・2階裏セクションの週別4名体制確保: 6日間の通常週において、特定週（月末など）に全日3名体制になることを防止し、各週に4名出勤日を均等分散（設定シートで最低日数指定可能）。

7. 公休の月内固定と月替わりローテーション (v1.6 / 空欄者自動適用)
   ・スタッフマスタの「希望公休曜日」に記入があるスタッフは、その指定曜日を月内固定（現行維持）。
   ・「希望公休曜日」が空欄のスタッフ（正社員・週4勤務者など）に対しては、平日（月〜金）の中で自動的に各人の主公休曜日が決定され、月内はその曜日に公休が固定されます。
   ・月が変わると、前月とは異なる平日へと自動的にローテーションされ、曜日による不公平感を解消します。
   ・「設定」シートの「空欄公休ローテーション」で「有効」「無効」の切り替えが可能です。

8. 祝日週の最低1日公休ルール (v1.5)
   ・祝日により週内の診療可能日数（月〜土）が5日となる週において、
     週5日勤務・週4日勤務、固定公休の有無を問わず、コアスタッフ全員に最低1日は公休日が設定されます（＝最大4日勤務、5連勤を防止）。
   ・固定公休（AND型）のスタッフについては、祝日と固定公休が重なった場合でも、その週内の平日に自動的に振替公休が設定されます。
   ・「設定」シートの「祝日週_公休設定」で「有効」「無効」を切り替えることも可能です。

9. 制約レベル（10段階の優先度指定）
   「シフト制約条件」シートの「制約レベル」列で、以下の優先度を自由に指定できます：
   ・HARD1: 最重要HARD（手術日専門スタッフ配置など、絶対に欠かせない制約）
   ・HARD2 (または HARD): 通常HARD（グループ出勤必須など）
   ・HARD3: 緩和可HARD（基本厳守だが、HARD同士衝突時に優先して不足を許容）
   ・HIGH1: 最優先HIGH（手術日の出勤人数指定など、HARD直下の強力な要件）
   ・HIGH2 (または HIGH): 通常HIGH（標準的な推奨人数指定など）
   ・HIGH3: 平準化優先HIGH（平日の出勤体制など、平準化よりは優先したい要件）
   ・SOFT1 / SOFT2 / SOFT3: 通常の希望（SOFT1=強め、SOFT2=普通、SOFT3=軽め）
   ・LOW: 努力目標（できればこうしたいレベル）

10. 各シートの役割
   ・スタッフマスタ: スタッフの氏名、所属、雇用形態、公休曜日、有休日、指定公休日などを管理
   ・シフト制約条件: 医療・業務ルール（上記10段階レベル対応）
   ・手術スケジュール: 手術日程（記載のある月がすべてGUIの対象月として選択可能）
   ・前月シフト実績: 前月の確定シフト表（月またぎ連動用）
   ・設定: 2階裏人数、連勤上限、各種ペナルティ、祝日週公休設定、週単位平準化、空欄公休ローテーション、指定公休日有効などの微調整パラメータ（15項目）

11. シフトの生成
   画面で「勤務条件表」が認識されていることを確認し、
   「シフト自動生成を開始」ボタンをクリックします。
   生成が完了すると、自動的に「YY年MM-MM月シフト.xlsx」が出力されます。
"""
    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(readme_content)
    print(f"使い方.txtを作成しました: {readme_path}")
    
    # 3. ZIPアーカイブの作成
    zip_name = "シフト_v1.9.zip"
    if os.path.exists(zip_name):
        os.remove(zip_name)
        
    print(f"ZIPアーカイブ '{zip_name}' を作成中...")
    with zipfile.ZipFile(zip_name, 'w', zipfile.ZIP_DEFLATED) as zipf:
        for root, dirs, files in os.walk(dist_dir):
            for file in files:
                abs_path = os.path.join(root, file)
                rel_path = os.path.relpath(abs_path, dist_dir)
                zipf.write(abs_path, rel_path)
                
    zip_size_mb = os.path.getsize(zip_name) / (1024 * 1024)
    print(f"★ 配布パッケージ作成完了: {zip_name} ({zip_size_mb:.1f} MB)")

if __name__ == "__main__":
    package()
